std::span<const PresetProgram> builtin_programs() noexcept { return kPresets; }

const PresetProgram *find_builtin_program(std::string_view id_or_index) noexcept {
  if (id_or_index.empty()) {
    return nullptr;
  }
  for (const auto &p : kPresets) {
    if (p.id == id_or_index) {
      return &p;
    }
  }
  if (id_or_index.size() == 1 && id_or_index[0] >= '1' &&
      id_or_index[0] <= static_cast<char>('0' + kPresets.size())) {
    const auto idx = static_cast<std::size_t>(id_or_index[0] - '1');
    return &kPresets[idx];
  }
  return nullptr;
}

