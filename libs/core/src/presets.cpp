std::span<const PresetProgram> builtin_programs() noexcept { return kPresets; }

const PresetProgram *find_builtin_program(std::string_view id_or_index) noexcept {
  if (id_or_index.empty()) {
    return nullptr;
  }
  for (const auto &p : kPresets) {
    if (p.id == id_or_index) {
      return &p;
    }
  }
  int number = 0;
  for (const char ch : id_or_index) {
    if (ch < '0' || ch > '9') {
      return nullptr;
    }
    number = number * 10 + (ch - '0');
    if (number > static_cast<int>(kPresets.size())) {
      return nullptr;
    }
  }
  if (number >= 1) {
    return &kPresets[static_cast<std::size_t>(number - 1)];
  }
  return nullptr;
}

